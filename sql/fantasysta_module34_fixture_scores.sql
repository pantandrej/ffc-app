-- ============================================================================
-- FANTASYСТА — Модуль 34. Счёт матча в календаре
-- Раньше club_fixtures хранил только время и участников — на "Календаре"
-- сыгранные матчи выглядели так же, как и будущие. Добавляем счёт (по нему же
-- считаются и club_results, но там агрегат по клубу, а не по матчу), чтобы
-- игрок видел результат прямо в календаре, не уходя на другую страницу.
-- ============================================================================

ALTER TABLE public.club_fixtures
  ADD COLUMN IF NOT EXISTS home_score SMALLINT,
  ADD COLUMN IF NOT EXISTS away_score SMALLINT;

NOTIFY pgrst, 'reload schema';

-- Страховка: если какой-то клуб не совпал по имени — узнаем сразу, а не когда
-- игрок откроет пустую корзину.
DO $$
DECLARE missing_count INTEGER;
BEGIN
  SELECT count(*) INTO missing_count FROM public.clubs WHERE pot IS NULL;
  IF missing_count > 0 THEN
    RAISE EXCEPTION '% клубов остались без корзины — проверь названия', missing_count;

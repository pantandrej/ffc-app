// Общий помощник для показа ошибок пользователю. Отдельно ловим "JWT issued
// at future" — это не баг в коде, а рассинхронизация часов на устройстве
// пользователя (Supabase сверяет "выпущен в" токена с текущим временем
// устройства; если часы отстают — любой токен кажется "из будущего").
export function friendlyError(e) {
  const raw = e?.message || String(e || "Неизвестная ошибка");
  if (/issued at future|jwt.*future/i.test(raw)) {
    return "Не получилось загрузить данные — на устройстве неверно выставлены дата и время. Проверь их в настройках (поставь «автоматически») и зайди заново.";
  }
  return raw;
}
